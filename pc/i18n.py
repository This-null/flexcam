def detect_lang():
    code = ""
    try:
        code = (locale.getlocale()[0] or "").lower()
    except Exception:
        code = ""
    if not code:
        try:
            code = (locale.getdefaultlocale()[0] or "").lower()
        except Exception:
            code = ""
    for lang in STRINGS:
        if code.startswith(lang) or f"_{lang}" in code or lang in code[:3]:
            return lang
    return "en"


class T:
    def __init__(self, lang=None):
        self.lang = lang if lang in STRINGS else detect_lang()

    def __call__(self, key):
        table = STRINGS.get(self.lang, STRINGS["en"])
        return table.get(key) or STRINGS["en"].get(key, key)
